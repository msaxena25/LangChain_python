from typing import Any
from langchain_chroma import Chroma


from langchain_google_genai import GoogleGenerativeAIEmbeddings
from langchain_core.documents import Document

documents  = [
    Document(
        page_content="Python is a programming language used for AI and machine learning.",
        metadata={"topic": "Python", "source": "notes_1"},
        id="doc_1" # optional but recommended to add id to the documents while adding them to the vector store.
    ),
    Document(
        page_content="ChromaDB stores vector embeddings and supports similarity search.",
        metadata={"topic": "Vector Database", "source": "notes_2"},
        id="doc_2"
    ),
    Document(
        page_content="LangChain helps developers build applications using language models.",
        metadata={"topic": "LangChain", "source": "notes_3"},
        id="doc_3"
    ),
    Document(
        page_content="Semantic search finds information based on meaning rather than exact words.",
        metadata={"topic": "Search", "source": "notes_4"},
        id="doc_4"
    )
]


from dotenv import load_dotenv

import os
load_dotenv()

# Load the environment variables
GOOGLE_API_KEY = os.getenv("GOOGLE_API_KEY")

embedding_model = GoogleGenerativeAIEmbeddings(
    model="gemini-embedding-001",
    google_api_key=os.getenv("GOOGLE_API_KEY")
    )

# lets create vector_store 

vector_store = Chroma(
    collection_name="learning_notes",
    persist_directory="./chromadb", # foldername where chromedb will store.
    embedding_function=embedding_model
)


# now add our documents to this store
# add_documents() returns a list of ids of the added documents
# these ids are generated by chromadb itself If we dont provide ids with documents.
added_documents_ids = vector_store.add_documents(documents=documents)
print('added_documents_ids', added_documents_ids)
# added_documents_ids ['doc_1', 'doc_2', 'doc_3', 'doc_4']

print('collection_name', vector_store._collection.name) #learning_notes
print('directory_name', vector_store._client.get_settings().persist_directory) #./chromadb

print("Documents added to ChromaDB")

#view documents in the vector store

documents = vector_store.get()
print('documents', documents)
'''
documents {'ids': ['doc_1', 'doc_2', 'doc_3', 'doc_4'], 'embeddings': None, 'documents': ['Python is a programming language used for AI and machine learning.', 'ChromaDB stores vector embeddings and supports similarity search.', 'LangChain helps developers build applications using language models.', 'Semantic search finds information based on meaning rather than exact words.'], 'uris': None, 'included': ['metadatas', 'documents'], 'data': None, 'metadatas': [{'topic': 'Python', 'source': 'notes_1'}, {'source': 'notes_2', 'topic': 'Vector Database'}, {'topic': 'LangChain', 'source': 'notes_3'}, {'source': 'notes_4', 'topic': 'Search'}]}
'''

#view documents with metadata
documents = vector_store.get(include=["documents", "metadatas"])
print('documents with metadata', documents)
'''
documents with metadata {'ids': ['doc_1', 'doc_2', 'doc_3', 'doc_4'], 'embeddings': None, 'documents': ['Python is a programming language used for AI and machine learning.', 'ChromaDB stores vector embeddings and supports similarity search.', 'LangChain helps developers build applications using language models.', 'Semantic search finds information based on meaning rather than exact words.'], 'uris': None, 'included': ['documents', 'metadatas'], 'data': None, 'metadatas': [{'topic': 'Python', 'source': 'notes_1'}, {'topic': 'Vector Database', 'source': 'notes_2'}, {'topic': 'LangChain', 'source': 'notes_3'}, {'topic': 'Search', 'source': 'notes_4'}]}
'''

#view documents in the vector store by query - similarity_search
# k is the number of documents to return
documents = vector_store.similarity_search(query="What is Python?", k=2)
print('documents by query', documents)
'''
documents by query [Document(id='doc_1', metadata={'source': 'notes_1', 'topic': 'Python'}, page_content='Python is a programming language used for AI and machine learning.'), Document(id='doc_3', metadata={'source': 'notes_3', 'topic': 'LangChain'}, page_content='LangChain helps developers build applications using language models.')]
'''

# similarity_search with score - similarity_search_with_score

documents = vector_store.similarity_search_with_score(query="What is Python?", k=2)
print('documents by query with score', documents)
'''
documents by query with score [(Document(id='doc_1', metadata={'topic': 'Python', 'source': 'notes_1'}, page_content='Python is a programming language used for AI and machine learning.'), 0.5630801320075989), (Document(id='doc_3', metadata={'source': 'notes_3', 'topic': 'LangChain'}, page_content='LangChain helps developers build applications using language models.'), 0.7989264130592346)]
'''

# use filter in similarity_search_with_score
# filter options - topic, source, id (associated metadata values)
documents = vector_store.similarity_search(
    query="", k=1, filter={"topic": "LangChain"})

print('documents using filter', documents)
'''
documents using filter [Document(id='doc_3', metadata={'source': 'notes_3', 'topic': 'LangChain'}, page_content='LangChain helps developers build applications using language models.')]
'''


#--------------------------------------------------------------------

# Now lets Check document's Embedding already exists in the vector store or not

# First extract Ids from documents list
document_ids: list[str | None] =  [doc.id for doc in documents]
print('document_ids', document_ids)
# document_ids ['doc_1', 'doc_2', 'doc_3', 'doc_4']

# Now check if the embeddings already exist in the vector store
embeddings_ids: dict[str, Any] = vector_store.get(ids=document_ids)["ids"]
print('embeddings_ids', embeddings_ids)
# embeddings_ids ['doc_1', 'doc_2', 'doc_3', 'doc_4']

# Now find the new ids which need to be added to the vector store

new_docs = [doc for doc in document_ids if doc.id not in embeddings_ids]
print('new_docs', new_docs)
# new_ids []

if new_docs:
    new_added_docs_ids = vector_store.add_documents(documents=new_docs)
    print('New documents added to the vector store', new_added_docs_ids)
else:
    print('All documents already exist in the vector store')

# update documents in the vector store

document= Document(page_content="Python is a programming language used for AI and machine learning.", 
metadata={"topic": "Python", "source": "notes_1"}, id="doc_1")

vector_store.update_document(document_id="doc_1", document=document)

vector_store.update_documents(ids=["doc_1"], documents=[document])

# delete documents from the vector store

vector_store.delete(ids=["doc_1"])

vector_store.delete(ids=["doc_1", "doc_2", "doc_3"])